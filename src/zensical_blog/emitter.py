# ---------------------------------------------------------------------------
# Nav assurance (US5)
# ---------------------------------------------------------------------------


def _check_nav(model: BlogModel) -> BuildWarning | None:
    """Return a warning if the Blog nav entry is absent from ``mkdocs.yml``."""
    config = model.config
    mkdocs_yml = config.docs_dir.parent / "mkdocs.yml"
    if not mkdocs_yml.is_file():
        return None  # No mkdocs.yml — no nav to check

    from ruamel.yaml import YAML

    yaml = YAML()
    with open(mkdocs_yml, encoding="utf-8") as fh:
        data = yaml.load(fh) or {}

    nav = data.get("nav") or []
    for entry in nav:
        if isinstance(entry, dict):
            for label, path in entry.items():
                if label == config.nav_label and path == config.nav_path:
                    return None

    return BuildWarning(
        code="MISSING_NAV_ENTRY",
        message=(
            f"Blog nav entry not found in mkdocs.yml. "
            f"Add `- {config.nav_label}: {config.nav_path}` to your nav, "
            f"or run `zensical-blog build --apply-nav` to patch it automatically."
        ),
    )


# ---------------------------------------------------------------------------
# Top-level orchestrator
# ---------------------------------------------------------------------------


def emit_all(model: BlogModel) -> None:
    """Emit all blog pages for *model*.

    Orchestration order:
    1. Blog index
    2. Archive landing + per-year pages
    3. Tags landing + per-tag pages
    4. Categories landing + per-category pages
    5. Nav assurance check (warning only, no writes)
    """
    config = model.config

    # Ensure generated root exists
    config.generated_root.mkdir(parents=True, exist_ok=True)

    emit_blog_index(model)

    if config.enable_archive_landing:
        emit_archive_landing(model)
        for period in model.archives:
            emit_archive_year(model, period)

    if config.enable_tags:
        emit_tags_landing(model)
        for term in model.tags:
            emit_tag_page(model, term)

    if config.enable_categories:
        emit_categories_landing(model)
        for term in model.categories:
            emit_category_page(model, term)

    nav_warning = _check_nav(model)
    if nav_warning:
        log.warning(nav_warning.message)
